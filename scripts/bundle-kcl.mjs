// Generates configurator/js/kcl-bundle.js — the single-file KCL bundle used by
// the configurator's live Engine API mode.
//
//   node scripts/bundle-kcl.mjs
//
// Output: configurator/js/kcl-bundle.js  (ES module, exports KCL_BUNDLE)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { bundleProject } from './lib/bundle.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const outFile = path.join(root, 'configurator', 'js', 'kcl-bundle.js')

const code = bundleProject(root, 'main.kcl')

const out = `// AUTO-GENERATED by scripts/bundle-kcl.mjs — do not edit.
// Single-file KCL project (main.kcl + transitive imports) for the Zoo Engine API.
// Regenerate with: node scripts/bundle-kcl.mjs
export const KCL_BUNDLE = ${JSON.stringify(code, null, 2)}
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, out)

const importLines = code.split('\n').filter((l) => l.trim().startsWith('import '))
const settingsLines = code.split('\n').filter((l) => l.trim().startsWith('@settings'))
console.log(`wrote ${outFile}`)
console.log(`  total lines : ${code.split('\n').length}`)
console.log(`  import lines: ${importLines.length}`)
console.log(`  @settings   : ${settingsLines.length}`)
if (importLines.length > 0) {
  console.error('WARNING: leftover import statements in bundle:')
  for (const l of importLines) console.error('  ' + l.trim())
  process.exit(1)
}
